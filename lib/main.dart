Future<void> main() async {
  WidgetsFlutterBinding.ensureInitialized();
  await Firebase.initializeApp(options: DefaultFirebaseOptions.currentPlatform);
  if (AppConstants.useSupabaseStorage) {
    await Supabase.initialize(
      url: AppConstants.supabaseUrl,
      anonKey: AppConstants.supabasePublishableKey,
    );
  }
  final themeProvider = await ThemeProvider.load();
  runApp(FixTrailApp(themeProvider: themeProvider));
}

class FixTrailApp extends StatelessWidget {
  final ThemeProvider themeProvider;
  const FixTrailApp({super.key, required this.themeProvider});

  @override
  Widget build(BuildContext context) {
    return MultiProvider(
      providers: [
        ChangeNotifierProvider<ThemeProvider>.value(value: themeProvider),
        ChangeNotifierProvider(create: (_) => AuthProvider(AuthService())),
        // IncidentProvider is re-bound whenever the signed-in profile changes.
        ChangeNotifierProxyProvider<AuthProvider, IncidentProvider>(
          create: (_) => IncidentProvider(IncidentService()),
          update: (_, auth, prev) => prev!..bind(auth.profile),
        ),
      ],
      child: Consumer<ThemeProvider>(builder: (context, theme, _) {
        // Palette getters read this flag, so set it before building the UI.
        AppColors.dark = theme.isDark;
        return MaterialApp(
          // New key on toggle => whole tree rebuilds with the new palette.
          key: ValueKey(theme.isDark),
          title: AppConstants.appName,
          debugShowCheckedModeBanner: false,
          theme: buildTheme(),
          home: const AuthGate(),
        );
      }),
    );
  }
}

/// Chooses the screen from the auth state (session handling).
class AuthGate extends StatelessWidget {
  const AuthGate({super.key});

  @override
  Widget build(BuildContext context) {
    final status = context.select<AuthProvider, AuthStatus>((a) => a.status);
    final Widget child;
    switch (status) {
      case AuthStatus.loading:
        child = Scaffold(
            body: Center(child: CircularProgressIndicator(color: AppColors.teal)));
        break;
      case AuthStatus.signedOut:
        child = const AuthScreen();
        break;
      case AuthStatus.needsVerification:
        child = const VerifyEmailScreen();
        break;
      case AuthStatus.ready:
        child = const AppShell();
        break;
    }
    return KeyedSubtree(key: ValueKey(status), child: child);
  }
}
